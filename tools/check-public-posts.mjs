import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { gunzipSync } from "node:zlib";
import { filterDetailedRegulations, filterDetailedNotices, defaultDetailSettings } from "../packages/common/src/regulations/regulation-detail-ui.ts";
const require = createRequire(new URL("../apps/public-site/package.json", import.meta.url));
const ts = require("typescript");
const source = await readFile(new URL("../packages/common/src/regulations/public-posts.ts", import.meta.url), "utf8");
const js = ts.transpile(source, { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 }).replace('"./index"', JSON.stringify(new URL("../packages/common/src/regulations/index.ts", import.meta.url).href));
const { filterPublicPosts } = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"));
const posts = JSON.parse(await readFile(new URL("../apps/public-site/data/public-posts.json", import.meta.url), "utf8"));
const external = JSON.parse(await readFile(new URL("../apps/public-site/data/external-public-posts.json", import.meta.url), "utf8"));
const bytes = await readFile(new URL("../apps/public-site/data/public-snapshot-v2.json.gz", import.meta.url));
assert.equal(createHash("sha256").update(bytes).digest("hex"), "9a321e744da33cdfd11737337c1e2b48abc1ed4b1c4aea2f5dfe1e72ff49ca38");
const snapshot = JSON.parse(gunzipSync(bytes));
assert.equal(snapshot.rows.length, 1041); assert.equal(snapshot.notices.length, 2089);
const target = filterPublicPosts(posts, "감사").find(p => p.board_id === "44" && p.post_id === "64613");
assert.ok(target); assert.equal(target.posted_date, "2016-12-08");
assert.ok(filterPublicPosts(posts, "기타소송 업무처리 실태 감사결과 보고서").some(p => p.post_id === "64613"));
assert.deepEqual(filterPublicPosts([], "감사"), []);
const fixture = { ...target, body: "본문전용토큰", body_available: false };
assert.equal(filterPublicPosts([fixture], "본문전용토큰").length, 0);
assert.equal(filterPublicPosts([{ ...fixture, body_available: true }], "본문전용토큰").length, 1);
const sources = new Map(); for (const s of snapshot.sources) sources.set(s.regulation_version_id, [...(sources.get(s.regulation_version_id) ?? []), s]);
const names = new Map(snapshot.rows.map(r => [r.regulation_version_id, r.display_name]));
const results = [];
for (const q of ["감사", "구상권", "구상금", "채권관리", "소송", "책임경영", "소송위임"]) results.push({ query: q, regulations: filterDetailedRegulations(snapshot.rows,q,defaultDetailSettings("master"),new Map(),sources).length, notices: filterDetailedNotices(snapshot.notices,q,defaultDetailSettings("notice"),names).length, posts: filterPublicPosts(posts,q).length, external: filterPublicPosts(external,q).length });
assert.equal(results[0].regulations,18); assert.equal(results[0].notices,41);
console.table(results); console.log("PASS: independent posts, attachment/body search, empty data, unchanged snapshot");
